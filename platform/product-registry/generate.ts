function renderProductAgentSeedsFile(products: readonly DiscoveredProduct[]): string {
  const registrations = products.flatMap((product) => product.manifest.agents
    .filter((agent) => agent.seedOnStartup === true && Boolean(agent.seedModule))
    .map((agent, index) => ({
      importName: `create${toManifestExportName(product.productId)}AgentSeed${index}`,
      importPath: `../${product.productId}/${agent.seedModule!.replace(/^\.\//, '')}`,
      productId: product.productId
    })))
  const imports = registrations.map((entry) => `import { createProductAgentSeed as ${entry.importName} } from '${entry.importPath}'`).join('\n')
  const entries = registrations.map((entry) => `  { productId: ${JSON.stringify(entry.productId)}, create: ${entry.importName} }`).join(',\n')
  return `/* eslint-disable */
// This file is generated by scripts/generate-product-registry.mts. Do not edit by hand.

import type { ProductAgentSeedFactory } from '@platform/ai/agent-platform/seeds/mergeAgentSeeds'
${imports}

export const productAgentSeedFactories = [
${entries}
] as const satisfies readonly ProductAgentSeedFactory[]
`
}

export async function generateProductRegistry(options: GenerateProductRegistryOptions): Promise<GeneratedProductRegistry> {
  const outputDir = options.outputDir ?? resolve(options.workspaceRoot, 'products/generated')
  const products = await discoverProductManifests(options.workspaceRoot)
  const registry = buildGeneratedProductRegistry(products)

  mkdirSync(outputDir, { recursive: true })
  writeFileSync(join(outputDir, 'productManifests.ts'), renderProductManifestsFile(products), 'utf8')
  writeFileSync(join(outputDir, 'shellRegistry.ts'), renderShellRegistryFile(products, registry), 'utf8')
  writeFileSync(join(outputDir, 'productServices.ts'), renderProductServicesFile(products), 'utf8')
  writeFileSync(join(outputDir, 'productAgentSeeds.ts'), renderProductAgentSeedsFile(products), 'utf8')

  return registry
}

export function assertGeneratedArtifactsExist(workspaceRoot: string): void {
  const outputDir = resolve(workspaceRoot, 'products/generated')
  for (const fileName of ['productManifests.ts', 'shellRegistry.ts', 'productServices.ts', 'productAgentSeeds.ts']) {
    const filePath = resolve(outputDir, fileName)
    if (!existsSync(filePath)) {
      throw new ProductRegistryValidationError(
        `Missing generated artifact ${filePath}. Run "pnpm generate:products" before dev, build, test, or typecheck.`
      )
    }
  }
}

export async function generateProductRegistryArtifacts(options: GenerateProductRegistryOptions): Promise<GeneratedProductRegistry> {
  return generateProductRegistry(options)
}

/**
 * 跨产品的事件话题守卫（`MI-11-R22` A1，架构师 2026-11-01 要求与目录同批）。
 *
 * 两条，都是「合并之前先解决歧义」：
 * 1. 一个 topic 只能由一个产品声明——两个产品声明同一个 topic，订阅目录就说不清是谁发布的；
 * 2. 消费声明必须落在某产品的发布声明里——消费别家的话题合法，但话题本身必须被某处声明过，
 *    否则订阅校验会把一个合法的消费判成非法。
 */
function assertCrossProductEventTopics(products: readonly DiscoveredProduct[]): void {
  const publisherByTopic = new Map<string, string>()

  for (const product of products) {
    for (const topic of product.manifest.eventTopics ?? []) {
      const existing = publisherByTopic.get(topic)
      if (existing && existing !== product.productId) {
        throw new ProductRegistryValidationError(
          `event topic "${topic}" is declared by both "${existing}" and "${product.productId}"; a topic has exactly one publisher`
        )
      }
      publisherByTopic.set(topic, product.productId)
    }
  }

  for (const product of products) {
    for (const consumer of product.manifest.eventConsumers ?? []) {
      for (const topic of consumer.topics ?? []) {
        if (!publisherByTopic.has(topic)) {
          throw new ProductRegistryValidationError(
            `product "${product.productId}" consumer "${consumer.id}" subscribes to an undeclared event topic: ${topic}`
          )
        }
      }
    }
  }
}
