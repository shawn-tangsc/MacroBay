import type { GeneratedProductRegistry } from './types'
import type { DiscoveredProduct } from './generate'

/**
 * 把注册表渲染成源码文本（`shellRegistry.ts` / `productManifests.ts`）。
 *
 * 从 `generate.ts` 抽出来是因为那个文件已越过体积线：这里是**纯字符串拼装**，不读文件、不校验、
 * 不决定生成什么——数据在 `generate.ts`，形状在这里。两边各自可读，改一处不必翻另一个 500 行。
 */

export function renderProductManifestsFile(products: readonly DiscoveredProduct[]): string {
  const imports = products
    .map((product) => `import { ${product.exportName} } from '../${product.productId}/product.manifest'`)
    .join('\n')
  const entries = products.map((product) => product.exportName).join(', ')
  const manifestArray = products.length > 0 ? `[${entries}] as const` : '[] as const'

  return `/* eslint-disable */
// This file is generated by scripts/generate-product-registry.ts. Do not edit by hand.

${imports}

export const productManifests = ${manifestArray}
`
}

export function renderShellRegistryFile(_products: readonly DiscoveredProduct[], registry: GeneratedProductRegistry): string {
  const panelEntries = registry.panelEntries.map((entry) => {
    const importPath = `../${entry.productId}/${entry.modulePath.replace(/^\.\//, '')}`
    return `  {
    productId: ${JSON.stringify(entry.productId)},
    registration: ${JSON.stringify(entry.registration)},
    load: () => import(${JSON.stringify(importPath)})
  }`
  }).join(',\n')
  const menuEntries = registry.menuEntries
    .map((entry) => {
      const importPath = `../${entry.productId}/${entry.modulePath.replace(/^\.\//, '')}`
      return `  {
    id: ${JSON.stringify(entry.id)},
    productId: ${JSON.stringify(entry.productId)},
    productName: ${JSON.stringify(entry.productName)},
    title: ${JSON.stringify(entry.title)},
    icon: ${JSON.stringify(entry.icon)},
    order: ${entry.order},
    routePath: ${JSON.stringify(entry.routePath)},
    workspace: ${JSON.stringify(entry.workspace)},
${entry.home === true ? '    home: true,\n' : ''}    load: () => import(${JSON.stringify(importPath)})
  }`
    })
    .join(',\n')

  const windowEntries = registry.windowEntries
    .map((entry) => {
      const importPath = `../${entry.productId}/${entry.modulePath.replace(/^\.\//, '')}`
      return `  {
    id: ${JSON.stringify(entry.id)},
    productId: ${JSON.stringify(entry.productId)},
    load: () => import(${JSON.stringify(importPath)})
  }`
    })
    .join(',\n')

  const settingsEntries = registry.settingsEntries
    .map((entry) => {
      const importPath = `../${entry.productId}/${entry.modulePath.replace(/^\.\//, '')}`
      return `  {
    id: ${JSON.stringify(entry.id)},
    productId: ${JSON.stringify(entry.productId)},
    productName: ${JSON.stringify(entry.productName)},
    title: ${JSON.stringify(entry.title)},
    icon: ${JSON.stringify(entry.icon)},
    order: ${entry.order},
${entry.navIntent === undefined ? '' : `    navIntent: ${JSON.stringify(entry.navIntent)},\n`}    load: () => import(${JSON.stringify(importPath)})
  }`
    })
    .join(',\n')

  return `/* eslint-disable */
// This file is generated by scripts/generate-product-registry.ts. Do not edit by hand.

import type { GeneratedProductMenuEntry, GeneratedProductSettingsEntry, GeneratedProductPanelEntry, GeneratedProductSettingsDrawerEntry, GeneratedProductWindowEntry } from '@platform/product-registry/types'
import type { LocalizedText } from '@platform/product-manifest'

export const productMenuEntries = [
${menuEntries}
] as const satisfies readonly GeneratedProductMenuEntry[]

export const productSettingsEntries = [
${settingsEntries}
] as const satisfies readonly GeneratedProductSettingsEntry[]

/**
 * 一次性窗口入口：主进程起隐藏窗口时按 (productId, id) 取它，加载后自己拿默认导出渲染。
 * 不进菜单、不进路由，也不参与「哪一页是首页」。
 */
export const productWindowEntries = [
${windowEntries}
] as const satisfies readonly GeneratedProductWindowEntry[]

export const productApprovalFieldLabels: Readonly<Record<string, Readonly<Record<string, LocalizedText>>>> = ${JSON.stringify(registry.approvalFieldLabels, null, 2)}

export const productPanelEntries = [
${panelEntries}
] as const satisfies readonly GeneratedProductPanelEntry[]

export const productIds = ${JSON.stringify(registry.productIds)}

export const productSettingsDrawers = ${JSON.stringify(registry.settingsDrawers, null, 2)} as const satisfies readonly GeneratedProductSettingsDrawerEntry[]
`
}

