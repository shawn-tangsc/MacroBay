import { randomUUID } from 'node:crypto'

/**
 * 主进程的**启动批次标识**：进程内生成一次，早于任何仓储构造，所有「写 pending」的地方都用它。
 *
 * 它回答的问题是：库里这条 `pending` 是哪一次主进程启动写的。崩溃收尾只收「不是本批次」的行——
 * 同一份 userData 同时只有一个进程（单实例锁），所以「不是本批次」就等于「上一个已经死掉的进程」，
 * 不需要心跳，也不需要时间。
 *
 * **不要用时间判**：boot 期间刚起的那次运行，开始时刻也早于收敛那一刻，按时间判会把它一起收掉；
 * 用户改系统时间同样会误收。窗口也不是归属维度——运行归主进程 runtime，窗口只是订阅者。
 */
export const processBootId = randomUUID()
