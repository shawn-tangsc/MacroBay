/**
 * 助手正文是 markdown，而飞书文本消息**不渲染**它：`**`、`#`、行首 `-` 会原样出现在读者手机上
 * （用户 2026-11-11 的截图）。投递前把控制符号转成纯文本。
 *
 * 三条边界：
 * - **只去符号，不删内容**：加粗/标题/列表的正文一字不丢；列表符号换成 `•` 保留“这是一项”；
 * - **一份实现**：只在投递层调用，不散到生成提示词里，也不在别处再写第二套；
 * - 只处理这些确定是控制符的形态（`**`、`__`、`~~`、行首 `#`、行首列表符号、代码围栏）。
 *   单星号斜体与 `[文字](链接)` 不动：它们在正文里可能本来就是字面字符，误删会丢内容。
 */
export function toLarkPlainText(text: string): string {
  return text
    // 代码围栏标记：保留里面的行，删掉 ``` 这一行本身。
    .replace(/^[ \t]*```.*$/gmu, '')
    // 标题：行首 1–6 个 # 加一个空格，删掉符号，保留标题文字。
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+/gmu, '')
    // 无序列表：行首的 - / * / + 换成一个项目符号，读者仍能看出这是列表。
    .replace(/^([ \t]*)[-*+][ \t]+/gmu, '$1• ')
    // 加粗与删除线：成对的符号去掉，里面的文字留下。
    .replace(/\*\*([^\n]+?)\*\*/gu, '$1')
    .replace(/__([^\n]+?)__/gu, '$1')
    .replace(/~~([^\n]+?)~~/gu, '$1')
}
