/**
 * 正文与「变更摘要」共用的一套数字读法。
 *
 * 校验器要判「正文里的这个数，应用是不是给模型看过」。正文是模型写的字符串，变更摘要是我们格式化
 * 出来的字符串——两边必须用**同一套**读法，否则就会出现「应用先把它印给模型看、再因为模型引用它
 * 而拒收」这种事（2026-11-11 的事故的一部分）。
 */

/**
 * 字符串里出现的百分数，**带符号**。
 *
 * 负号是数字的一部分：正文写「3 天 -2.75%」、事实是 `-2.74955757589076`，把负号吃掉就会拿 `2.75`
 * 去比 `-2.75`，判「快照里没有这个数」。
 *
 * 但 `3.75%-4.00%` 里的短横是**范围连接符**，不是负号——所以只有当它前面不是数字、不是百分号、
 * 也不是另一个破折号时才算负号。全角减号 `−` 一并认。
 */
export function percentagesIn(text: string): number[] {
  return [...text.matchAll(/(?<![\d%％–—])([-−])?(\d+(?:\.\d+)?)\s*(?:%|％)/gu)]
    .map(match => Number(`${match[1] === undefined ? '' : '-'}${match[2]}`))
    .filter(value => Number.isFinite(value))
}

/**
 * 字符串里的普通数字（不要求带百分号），同样带符号。
 *
 * 变更摘要的**值位**会印出「资金费率 = 0.007999」「73.43 亿美元」这类形状；模型照抄的是这个形状，
 * 只认百分数就会把这类值全判成「没出处」（架构师 2026-11-11 批：扩到普通数字，但只在值位）。
 */
export function numbersIn(text: string): number[] {
  return [...text.matchAll(/(?<![\d.])([-−])?(\d+(?:\.\d+)?)/gu)]
    .map(match => Number(`${match[1] === undefined ? '' : '-'}${match[2]}`))
    .filter(value => Number.isFinite(value))
}
