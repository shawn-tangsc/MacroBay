/**
 * 「这个组还给不给市场分析的重跑入口」——**一处定义**，三个调用点共用。
 *
 * 依据（用户 2026-11-18 定）：消息面（`sentiment`）组以后的分析一律走新闻解读、结果落在新闻抽屉。
 * 在卡片 / 时间轴 / 结论详情上点重跑，产出的是抽屉里那三段，卡片本身不会变——那就是「点了没反应
 * 的按钮」。所以按**组类别**决定这几处动作出现不出现；市场分析组的按钮、文案、行为逐字不变。
 *
 * 为什么写成函数而不是各处判 `=== 'sentiment'`：三处各写一次，改口径时必然漏一处；而且按按钮名字
 * 认（「立即分析」「重新分析」「重新生成」是三个名字）迟早认错。这里只回答一个问题：
 * **这个组类型的重跑动作该不该出现。** 出现之后它长什么样、点了做什么，与这里无关。
 */

/** 消息面组：分析结果落在新闻抽屉，主区这张卡不会被这次重跑改变。 */
const NEWS_DRIVEN_GROUP_TYPE = 'sentiment'

/**
 * 该组类型是否还提供市场分析的重跑入口。
 *
 * `groupType` 未知（老主进程没发、或行上没有组类型）时**保留**按钮：宁可多一个能用的按钮，
 * 也不要因为缺字段把一个正常入口藏掉——藏掉是读者找不回来的那种错。
 */
export function groupReanalysisOffered(groupType: string | null | undefined): boolean {
  return groupType !== NEWS_DRIVEN_GROUP_TYPE
}